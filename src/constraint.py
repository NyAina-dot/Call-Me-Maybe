"""Constrained decoding for function names and parameter values."""

from .utils import Tokenizer
from .models import FuncDefModel
from llm_sdk import Small_LLM_Model  # type: ignore[attr-defined]
import json
import numpy as np


class FunctionSelector:
    """Select a function name using constrained token generation."""

    def __init__(self, model: Small_LLM_Model, tokenizer: Tokenizer):
        """Initialize the selector with a model and tokenizer."""
        self.model = model
        self.tokenizer = tokenizer

    def build_prompt(
        self, prompt: str, functions: list[FuncDefModel]
    ) -> str:
        """Build the prompt used to select a function."""
        lines = [
            "You are a function-calling assistant. Given a user request, "
            "select the single best function from the list below.",
            "",
            "Available functions:",
        ]
        for function in functions:
            lines.append(f"- {function.name}: {function.description}")
        lines += ["", f"Request: {prompt}", "Function: "]
        return "\n".join(lines)

    def choose_function_name(
            self, prompt: str, functions: list[FuncDefModel]
    ) -> str:
        """Generate and return the best matching function name."""
        prompt_ids = self.tokenizer.text_to_token_ids(
            self.build_prompt(prompt, functions)
        )
        tree = self.tokenizer.function_names_token_tree(functions)
        generated_ids: list[int] = []
        while not self.tokenizer.is_complete(tree, generated_ids):
            logits = self.model.get_logits_from_input_ids(
                prompt_ids + generated_ids
            )
            allowed = self.tokenizer.get_allowed_tokens(tree, generated_ids)
            masked_logits = self.tokenizer.mask_logits(
                logits, allowed
            )
            next_id = max(allowed, key=lambda i: masked_logits[i])
            generated_ids.append(next_id)
        return self.tokenizer.token_ids_to_text(generated_ids)


class ParameterGenerator:
    """Generate typed function parameters using constrained decoding."""

    def __init__(
        self, model: Small_LLM_Model, tokenizer: Tokenizer
    ):
        """Initialize parameter generation state from the vocabulary."""
        self.model = model
        self.tokenizer = tokenizer

        self.string_tokens = [
            (token_id, token_text)
            for token_id, token_text in enumerate(
                tokenizer.id_to_text
            )
            if token_text
            and '"' not in token_text
            and all(ord(char) >= 32 for char in token_text)
        ]

        self.closing_quote_tokens = {
            token_id
            for token_id, token_text in enumerate(
                tokenizer.id_to_text
            )
            if token_text.startswith('"')
        }

        self.boolean_tokens: list[tuple[int, str]] = [
            (token_id, token_text)
            for token_id, token_text in enumerate(tokenizer.id_to_text)
            if token_text
            and ("true".startswith(token_text)
                 or "false".startswith(token_text))
        ]

    def build_prompt(
        self, prompt: str, function: FuncDefModel
    ) -> str:
        """Build the prompt used to extract function parameters."""
        parameters = {
            name: parameter.type
            for name, parameter in function.parameters.items()
        }
        print(f"processing {function.name}")

        return (
            "Extract the required arguments from the request.\n"
            "Preserve original text exactly. Never invent information.\n"
            "For regex, create ONE simple pattern matching the "
            "requested category, not individual matched values.\n\n"

            "EXAMPLE:\n"
            "Request: Replace numbers in 'I have 12 apples' with 'NUM'.\n"
            "Arguments: {\"source_string\":\"I have 12 apples\","
            "\"regex\":\"\\\\d+\",\"replacement\":\"NUM\"}\n"

            f"Function: {function.name}\n"
            f"Description: {function.description}\n"
            f"Parameters: {json.dumps(parameters)}\n\n"
            f"Request: {prompt}\n"
            "Arguments:"
        )

    def generate_parameters(
        self, prompt: str, function: FuncDefModel
    ) -> dict[str, float | int | str | bool]:
        """Generate all supported parameters for a function.

        Fixed parts (keys, separators) are written directly in the
        context; only the values are generated by the model, under
        constraints that depend on the type declared in the definition.

        Args:
            prompt: Natural language request.
            function: Definition of the chosen function.

        Returns:
            A dict mapping each parameter name to its generated value.

        Raises:
            ValueError: If a parameter type is not supported or a value
                cannot be generated.
        """
        tokens_ids = self.tokenizer.text_to_token_ids(
            self.build_prompt(prompt, function)
        )
        result: dict[str, float | int | str | bool] = {}
        parameter_names = list(function.parameters)
        negative_numbers = self.get_negative_number_flags(prompt)
        number_index = 0

        for index, name in enumerate(parameter_names):
            parameter = function.parameters[name]
            prefix = json.dumps(name) + ": "
            tokens_ids.extend(self.tokenizer.text_to_token_ids(prefix))

            value: float | int | str | bool
            if parameter.type in ("number", "integer"):
                value = self.generate_number(
                    tokens_ids,
                    integer=(parameter.type == "integer"),
                    require_negative=(
                        number_index < len(negative_numbers)
                        and negative_numbers[number_index]
                    ),
                )
                number_index += 1
            elif parameter.type == "string":
                value = self.generate_string(tokens_ids)
            elif parameter.type == "boolean":
                value = self.generate_boolean(tokens_ids)
            else:
                raise ValueError(
                    f"Unsupported parameter type: {parameter.type}"
                )
            result[name] = value
            tokens_ids.extend(
                self.tokenizer.text_to_token_ids(json.dumps(value))
            )
            if index < len(parameter_names) - 1:
                tokens_ids.extend(
                    self.tokenizer.text_to_token_ids(", ")
                )
        return result

    def get_negative_number_flags(self, text: str) -> list[bool]:
        """Return signs of numeric literals in appearance order."""
        flags: list[bool] = []
        index = 0

        while index < len(text):
            starts_number = text[index].isdigit() or (
                text[index] == "."
                and index + 1 < len(text)
                and text[index + 1].isdigit()
            )
            starts_negative_number = text[index] == "-" and (
                index + 1 < len(text)
                and (
                    text[index + 1].isdigit()
                    or (
                        text[index + 1] == "."
                        and index + 2 < len(text)
                        and text[index + 2].isdigit()
                    )
                )
            )

            if not (starts_number or starts_negative_number):
                index += 1
                continue

            number = "-" if starts_negative_number else ""
            if starts_negative_number:
                index += 1

            while index < len(text):
                candidate = number + text[index]
                if not self.is_number_prefix(candidate, False):
                    break
                number += text[index]
                index += 1

            flags.append(number.startswith("-"))

        return flags

    def is_number_prefix(
        self, text: str, integer: bool = False
    ) -> bool:
        """Return whether text can still become a valid number."""
        if text.startswith("-"):
            body = text[1:]
        else:
            body = text

        if integer:
            if body == "":
                return True
            if body.isascii() and body.isdigit():
                return True
            return False

        if body == "":
            return True

        left, dot, right = body.partition(".")

        if not (left.isascii() and left.isdigit()):
            return False

        if right != "":
            if not (right.isascii() and right.isdigit()):
                return False

        return True

    def get_allowed_number_tokens(
        self, generated_text: str, integer: bool,
        require_negative: bool = False,
    ) -> list[int]:
        """Return vocabulary tokens that preserve a valid number prefix."""
        allowed_tokens = []

        for token_id, token_text in enumerate(self.tokenizer.id_to_text):
            if not token_text:
                continue

            candidate = generated_text + token_text

            if (
                self.is_number_prefix(candidate, integer)
                and (not require_negative or generated_text or
                     candidate.startswith("-"))
            ):
                allowed_tokens.append(token_id)

        return allowed_tokens

    def is_complete_number(self, generated_text: str, integer: bool) -> bool:
        """Return whether generated_text is a complete JSON number."""
        if not generated_text:
            return False

        body = (
            generated_text[1:]
            if generated_text.startswith("-")
            else generated_text
        )
        if not body:
            return False

        if integer:
            return body.isascii() and body.isdigit()

        left, dot, right = body.partition(".")
        if not (left.isascii() and left.isdigit()):
            return False
        if not dot:
            return True
        return right.isascii() and right.isdigit()

    def generate_number(
        self, context_ids: list[int], integer: bool,
        require_negative: bool = False,
    ) -> float | int:
        """Generate a JSON number from the model's token probabilities."""
        generated_ids: list[int] = []
        generated_text = ""

        for _ in range(20):
            logits = self.model.get_logits_from_input_ids(
                context_ids + generated_ids
            )

            allowed_tokens = self.get_allowed_number_tokens(
                generated_text, integer, require_negative
            )
            number_is_complete = self.is_complete_number(
                generated_text, integer
            )
            termination_tokens = [
                token_id
                for token_id, token_text in enumerate(
                    self.tokenizer.id_to_text
                )
                if number_is_complete and token_text in (",", "}")
            ]
            allowed_tokens.extend(termination_tokens)

            if not allowed_tokens:
                raise ValueError(
                    f"Invalid or incomplete generated number: "
                    f"{generated_text!r}"
                )

            masked_logits = self.tokenizer.mask_logits(logits, allowed_tokens)

            next_token_id = max(
                range(len(masked_logits)),
                key=lambda i: masked_logits[i]
            )

            token_text = self.tokenizer.id_to_text[next_token_id]

            if token_text in (",", "}"):
                return (
                    int(generated_text)
                    if integer
                    else float(generated_text)
                )

            generated_ids.append(next_token_id)
            generated_text += token_text

        if not self.is_complete_number(generated_text, integer):
            raise ValueError(
                f"Number generation limit reached with an incomplete number: "
                f"{generated_text!r}"
            )

        return int(generated_text) if integer else float(generated_text)

    def is_valid_json_string_prefix(self, text: str) -> bool:
        """Return whether text is a valid, unfinished JSON string."""
        if not text.startswith('"'):
            return False

        escaped = False
        unicode_remaining = 0

        for char in text[1:]:
            if unicode_remaining > 0:
                if char not in "0123456789abcdefABCDEF":
                    return False
                unicode_remaining -= 1

            elif escaped:
                if char == "u":
                    unicode_remaining = 4
                elif char not in '"\\/bfnrt':
                    return False
                escaped = False

            elif char == "\\":
                escaped = True

            elif char == '"':
                return False

            elif ord(char) < 32:
                return False

        return True

    def get_allowed_string_tokens(
        self, generated_text: str
    ) -> list[int]:
        """Return vocabulary tokens valid after a string prefix."""
        allowed_tokens = []

        for token_id, token_text in self.string_tokens:
            candidate = generated_text + token_text

            if self.is_valid_json_string_prefix(candidate):
                allowed_tokens.append(token_id)

        return allowed_tokens

    def generate_string(
        self, context_ids: list[int], is_regex: bool = False
    ) -> str:
        """Generate a JSON string with constrained token decoding.

        Args:
            context_ids: Token ids of the context before the string value.
            is_regex: Whether to stop after detecting a repeated regex suffix.

        Returns:
            The generated string value.

        Raises:
            ValueError: If no valid token exists or generation is incomplete.
        """
        opening_quote_ids = self.tokenizer.text_to_token_ids('"')
        generated_ids = opening_quote_ids.copy()
        generated_text = '"'

        for _ in range(50):
            logits = self.model.get_logits_from_input_ids(
                context_ids + generated_ids
            )

            allowed_tokens = self.get_allowed_string_tokens(
                generated_text
            )

            try:
                json.loads(generated_text + '"')
                can_close = True
            except json.JSONDecodeError:
                can_close = False

            if can_close:
                allowed_tokens.extend(self.closing_quote_tokens)

            if not allowed_tokens:
                raise ValueError("No valid token available")

            masked_logits = self.tokenizer.mask_logits(
                logits, allowed_tokens
            )

            next_token_id = int(
                np.argmax(np.asarray(masked_logits))
            )

            if next_token_id in self.closing_quote_tokens:
                return str(json.loads(generated_text + '"'))

            token_text = self.tokenizer.id_to_text[next_token_id]

            generated_ids.append(next_token_id)
            generated_text += token_text

            if is_regex:
                content = generated_text[1:]

                for size in range(min(len(content) // 2, 12), 1, -1):
                    previous = content[-2 * size:-size]
                    current = content[-size:]

                    if previous == current:
                        generated_text = generated_text[:-size]
                        return str(json.loads(generated_text + '"'))

        try:
            return str(json.loads(generated_text + '"'))
        except json.JSONDecodeError:
            raise ValueError("String generation limit reached")

    def get_allowed_boolean_tokens(self, generated_text: str) -> list[int]:
        """Return the ids that keep generated_text a prefix of true/false.

        Args:
            generated_text: Boolean text generated so far.

        Returns:
            Ids of the tokens whose text continues "true" or "false".
        """
        allowed: list[int] = []
        for token_id, token_text in self.boolean_tokens:
            candidate = generated_text + token_text
            if "true".startswith(candidate) or "false".startswith(candidate):
                allowed.append(token_id)
        return allowed

    def generate_boolean(self, context_ids: list[int]) -> bool:
        """Generate a JSON boolean (true or false) with constrained decoding.

        At each step only the tokens that keep the text a prefix of
        "true" or "false" are allowed. Generation stops as soon as the
        text is exactly one of them. Neither word is a prefix of the
        other, so no extra terminator token is needed.

        Args:
            context_ids: Token ids of the context, ending right before
                the boolean value.

        Returns:
            The generated boolean.

        Raises:
            ValueError: If no valid token exists or the step limit is
                reached before a complete boolean.
        """
        generated_ids: list[int] = []
        generated_text = ""

        for _ in range(5):
            if generated_text in ("true", "false"):
                return generated_text == "true"

            logits = self.model.get_logits_from_input_ids(
                context_ids + generated_ids
            )
            allowed = self.get_allowed_boolean_tokens(generated_text)
            if not allowed:
                raise ValueError(
                    f"No valid token for boolean: {generated_text!r}"
                )

            masked = self.tokenizer.mask_logits(logits, allowed)
            next_id = int(np.argmax(masked))

            generated_ids.append(next_id)
            generated_text += self.tokenizer.id_to_text[next_id]

        if generated_text in ("true", "false"):
            return generated_text == "true"
        raise ValueError(
            f"Boolean generation limit reached: {generated_text!r}"
        )
